"""Ticket Review — search, triage, explain and overrule classifications.

Carries two required capabilities: the human-in-the-loop correction workflow,
and a full audit trail for any individual decision. Model predictions are kept
separately from reviewer decisions, so the evaluation pages still measure the
model rather than the person correcting it.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from driftguard import features
from driftguard.config import CLASS_DEFINITIONS, CLASSES
from driftguard.data import frame_to_csv_bytes
from driftguard.reporting import classified_export

from .. import charts, components as ui, state, theme

SORT_OPTIONS = {
    "Scope impact (largest first)": ("abs_impact", False),
    "Scope impact (smallest first)": ("abs_impact", True),
    "Confidence (lowest first)": ("confidence", True),
    "Confidence (highest first)": ("confidence", False),
    "Similarity (lowest first)": ("similarity", True),
    "Similarity (highest first)": ("similarity", False),
    "Ticket ID": ("ticket_id", True),
    "Date raised": ("created_date", True),
}


def render(result) -> None:
    classified = result.classified
    health = features.model_health(classified)
    unit = result.settings.size_unit.replace("_", " ")

    ui.page_header(
        "Ticket review",
        "Every classification, the evidence behind it, and the controls to "
        "overrule it.",
    )

    if state.is_synthetic():
        st.warning(
            "This project was generated by the synthetic test-data generator. "
            "Classifications here demonstrate behaviour; they say nothing "
            "about any real project.",
            icon="🧪",
        )

    ui.metric_row(
        [
            {"label": "Tickets", "value": theme.fmt_number(health["tickets"])},
            {
                "label": "Flagged for review",
                "value": theme.fmt_number(health["low_confidence"]),
                "footnote": f"{theme.fmt_percent(health['low_confidence_share'], 0)} below 0.50 confidence",
            },
            {
                "label": "Reviewed",
                "value": theme.fmt_number(health["reviewed"]),
                "footnote": f"{theme.fmt_percent(health['reviewed_share'], 0)} of tickets",
            },
            {
                "label": "Overturned",
                "value": theme.fmt_number(health["overturned"]),
                "footnote": "reviewer disagreed with the model",
                "delta_good": None,
            },
        ]
    )

    # ---- Review queue -----------------------------------------------------
    queue = features.review_queue(classified)
    if not queue.empty:
        ui.section(
            "Review queue",
            "Lowest-confidence classifications first — where the model is "
            "least sure and a reviewer adds the most value.",
        )
        queue_table = queue.rename(
            columns={
                "ticket_id": "Ticket",
                "title": "Title",
                "predicted_class": "Model said",
                "final_class": "Final",
                "confidence": "Confidence",
                "similarity": "Similarity",
                "matched_requirement_id": "Matched",
                "reviewed": "Reviewed",
            }
        )
        ui.data_table(
            ui.scale_to_percent(queue_table, ["Confidence"]),
            column_config={
                "Confidence": ui.percent_column(decimals=0),
                "Similarity": st.column_config.NumberColumn(format="%.3f"),
            },
        )

    ui.chart(charts.confidence_histogram(classified), key="rv_confidence")

    # ---- Search, filter, sort --------------------------------------------
    ui.section("All tickets", "Search, filter and sort the full ticket set.")

    view = classified.copy()
    view["abs_impact"] = view["net_contribution"].abs()

    row_one = st.columns([2, 2, 2])
    search = row_one[0].text_input(
        "Search", placeholder="Ticket ID or title…", key="rv_search"
    )
    chosen_classes = row_one[1].multiselect(
        "Classification", list(CLASSES), default=list(CLASSES), key="rv_classes"
    )
    review_filter = row_one[2].selectbox(
        "Review status",
        ["All", "Not reviewed", "Reviewed", "Overturned by reviewer", "Flagged (low confidence)"],
        key="rv_status",
    )

    row_two = st.columns([2, 2, 2])
    sort_label = row_two[0].selectbox("Sort by", list(SORT_OPTIONS), key="rv_sort")
    min_impact = row_two[1].number_input(
        f"Minimum absolute scope impact ({unit})",
        min_value=0.0,
        value=0.0,
        step=1.0,
        key="rv_minimpact",
    )
    high_impact_only = row_two[2].checkbox(
        "High-impact only",
        value=False,
        help="Tickets that individually move scope by at least 5% of the agreed baseline.",
        key="rv_highimpact",
    )

    if search:
        needle = search.strip().lower()
        mask = view["ticket_id"].astype(str).str.lower().str.contains(needle, na=False)
        if "title" in view.columns:
            mask |= view["title"].astype(str).str.lower().str.contains(needle, na=False)
        view = view[mask]

    view = view[view["final_class"].isin(chosen_classes)]

    if review_filter == "Not reviewed":
        view = view[~view["reviewed"]]
    elif review_filter == "Reviewed":
        view = view[view["reviewed"]]
    elif review_filter == "Overturned by reviewer":
        view = view[view["class_changed_by_reviewer"]]
    elif review_filter == "Flagged (low confidence)":
        view = view[view["confidence"] < 0.5]

    if min_impact > 0:
        view = view[view["abs_impact"] >= min_impact]

    if high_impact_only and not classified.empty:
        cutoff = features.high_impact_threshold(result.baseline_size)
        view = view[view["abs_impact"] >= max(cutoff, 1e-9)]
        st.caption(
            f"High-impact threshold: {cutoff:,.1f} {unit} — "
            f"{features.HIGH_IMPACT_SHARE:.0%} of the agreed baseline. A fixed "
            "share rather than a quantile, so the threshold does not move when "
            "a classification changes."
        )

    sort_column, ascending = SORT_OPTIONS[sort_label]
    if sort_column in view.columns:
        view = view.sort_values(sort_column, ascending=ascending, na_position="last")

    st.caption(f"Showing {len(view):,} of {len(classified):,} tickets.")

    columns = [
        c
        for c in (
            "ticket_id", "title", "final_class", "predicted_class", "confidence",
            "matched_requirement_id", "similarity", "final_size",
            "net_contribution", "reviewed",
        )
        if c in view.columns
    ]

    if view.empty:
        ui.empty_state(
            "No tickets match these filters",
            "Widen the classification filter, clear the search box, or lower "
            "the minimum scope impact.",
            icon="🔍",
        )
    else:
        table = view[columns].rename(
            columns={
                "ticket_id": "Ticket",
                "title": "Title",
                "final_class": "Class",
                "predicted_class": "Model said",
                "confidence": "Confidence",
                "matched_requirement_id": "Matched req",
                "similarity": "Similarity",
                "final_size": "Size",
                "net_contribution": "Scope impact",
                "reviewed": "Reviewed",
            }
        )
        ui.data_table(
            ui.scale_to_percent(table, ["Confidence"]),
            column_config={
                "Confidence": ui.percent_column(decimals=0),
                "Similarity": st.column_config.NumberColumn(format="%.3f"),
                "Size": st.column_config.NumberColumn(format="%.1f"),
                "Scope impact": st.column_config.NumberColumn(format="%+.1f"),
            },
            height=420,
        )

    ui.download_row(
        [
            (
                "Download filtered view (CSV)",
                frame_to_csv_bytes(classified_export(view.drop(columns=["abs_impact"], errors="ignore"))),
                "driftguard_tickets_filtered.csv",
                "text/csv",
            ),
            (
                "Download all classified tickets (CSV)",
                frame_to_csv_bytes(classified_export(classified)),
                "driftguard_classified_tickets.csv",
                "text/csv",
            ),
        ]
    )

    # ---- Explanation and override ----------------------------------------
    _render_explanation(result, view if not view.empty else classified)


def _render_explanation(result, candidates: pd.DataFrame) -> None:
    classified = result.classified
    thresholds = result.settings.thresholds

    ui.section(
        "Classification audit",
        "Everything behind one decision: the match, the evidence, the "
        "reasoning, and whether a human changed it.",
    )

    ticket_ids = list(candidates["ticket_id"].astype(str))
    if not ticket_ids:
        ui.empty_state("No ticket selected", "Adjust the filters above.", icon="🎫")
        return

    default_index = 0
    if st.session_state.get("selected_ticket") in ticket_ids:
        default_index = ticket_ids.index(st.session_state["selected_ticket"])
    selected = st.selectbox(
        "Ticket", ticket_ids, index=default_index, key="rv_ticket"
    )
    st.session_state["selected_ticket"] = selected

    row = classified.loc[classified["ticket_id"].astype(str) == selected].iloc[0]
    detail = features.explain_ticket(row, thresholds)

    left, right = st.columns([3, 2])

    with left:
        # 1-2. Identity
        st.markdown(f"### {detail['ticket_id']} — {detail['title']}")
        st.write(detail["description"])

        # 3-4. Prediction and final classification
        override_badge_html = (
            ui.severity_pill("Overridden by reviewer", theme.STATUS_SERIOUS, "✎")
            if detail["overridden"]
            else ui.severity_pill("Model prediction stands", theme.STATUS_GOOD, "✔")
        )
        st.markdown(
            f"<div style='margin:0.4rem 0 0.9rem 0'>{override_badge_html}</div>",
            unsafe_allow_html=True,
        )
        ui.data_table(
            pd.DataFrame(
                {
                    "Field": [
                        "Original model prediction",
                        "Final classification",
                        "Model confidence",
                        "Classifier",
                        "Size (as raised)",
                        "Size (confirmed)",
                    ],
                    "Value": [
                        detail["predicted_class"],
                        detail["final_class"],
                        f"{detail['confidence']:.0%}",
                        detail["classifier"],
                        f"{detail['size']:,.1f}",
                        f"{detail['final_size']:,.1f}",
                    ],
                }
            )
        )

        # 5-6. Matched requirement and similarity
        st.markdown("##### Matched baseline requirement")
        matched_title = detail["matched_requirement_title"]
        if isinstance(matched_title, str):
            st.markdown(f"**{detail['matched_requirement_id']} — {matched_title}**")
            st.caption(str(detail["matched_requirement_text"]))
        else:
            st.caption(f"Matched to {detail['matched_requirement_id']}.")

        ui.metric_row(
            [
                {
                    "label": "Similarity",
                    "value": f"{detail['similarity']:.3f}",
                    "footnote": detail["similarity_band"],
                },
                {
                    "label": "Margin over runner-up",
                    "value": f"{detail['match_margin']:.3f}",
                    "footnote": f"runner-up {detail['runner_up_id'] or '—'}",
                    "help_text": "A small margin means the match was nearly a tie.",
                },
            ]
        )

        # 7. Important matching terms
        st.markdown("##### Terms shared with that requirement")
        if detail["shared_terms"]:
            # Terms come from the TF-IDF vocabulary, which is built from the
            # uploaded ticket and requirement text.
            terms_html = ui.join_html(
                ui.SafeHtml(
                    f"<span class='dg-pill' style='background:{theme.ACCENT}1a;"
                    f"border-color:{theme.ACCENT}59;color:{theme.ACCENT_DARK};"
                    f"margin-right:0.3rem'>{ui.esc(term)}</span>"
                )
                for term in detail["shared_terms"]
            )
            st.markdown(terms_html, unsafe_allow_html=True)
        else:
            ui.no_evidence(
                "No distinctive vocabulary is shared with the nearest "
                "requirement, which is why the similarity is near zero."
            )
        st.caption(
            "These are TF-IDF terms — words weighted by how distinctive they "
            "are across this corpus. TF-IDF matches vocabulary, not meaning: "
            "it is not a language model and does not understand either text."
        )

        # 8. Keyword cue evidence
        st.markdown("##### Keyword cues triggered")
        cues = features.cue_evidence(str(row.get("text", "")))
        if cues.empty:
            st.caption(
                "No cue words fired. The classification therefore rests on the "
                "similarity score alone."
            )
        else:
            ui.data_table(cues[["Cue", "Signals"]])
            if detail["similarity"] < thresholds.weak_match:
                st.caption(
                    "Note the order of the rules: similarity below the "
                    f"weak-match threshold ({thresholds.weak_match:.2f}) is "
                    "checked *before* the cue logic, so these cues did not "
                    "decide this ticket."
                )

        # 9. Explanation
        st.markdown("##### Classification rationale")
        st.success(detail["rationale"])
        st.caption(detail["match_evidence"])

        alternatives = row.get("alternative_matches")
        if isinstance(alternatives, list) and len(alternatives) > 1:
            with st.expander("Other candidate requirements"):
                ui.data_table(
                    pd.DataFrame(
                        alternatives, columns=["Requirement", "Similarity"]
                    ).round(3),
                    column_config={
                        "Similarity": st.column_config.NumberColumn(format="%.3f")
                    },
                )

    # 10. Override controls
    with right:
        st.markdown("##### Reviewer decision")
        st.caption(
            "Corrections are stored separately from the prediction. The "
            "original stays on record, so evaluation still measures the model."
        )
        current = detail["final_class"]
        new_class = st.selectbox(
            "Classification",
            list(CLASSES),
            index=list(CLASSES).index(current) if current in CLASSES else 0,
            key=f"rv_class_{selected}",
        )
        st.caption(CLASS_DEFINITIONS[new_class])

        new_size = st.number_input(
            "Confirmed size",
            min_value=0.0,
            value=float(detail["final_size"]),
            step=1.0,
            key=f"rv_size_{selected}",
        )

        buttons = st.columns(2)
        if buttons[0].button("Save", type="primary", use_container_width=True):
            if new_class != detail["predicted_class"]:
                st.session_state.overrides[selected] = new_class
            else:
                st.session_state.overrides.pop(selected, None)
            if new_size != detail["size"]:
                st.session_state.size_overrides[selected] = new_size
            else:
                st.session_state.size_overrides.pop(selected, None)
            st.rerun()

        if buttons[1].button("Reset", use_container_width=True):
            st.session_state.overrides.pop(selected, None)
            st.session_state.size_overrides.pop(selected, None)
            st.rerun()

        reviewed_count = state.review_count()
        st.metric("Tickets reviewed", reviewed_count)
        if reviewed_count and st.button("Clear all reviews", use_container_width=True):
            st.session_state.overrides = {}
            st.session_state.size_overrides = {}
            st.rerun()

        if detail["overridden"]:
            st.info(
                f"The Scope Drift Index uses **{detail['final_class']}** for "
                f"this ticket. The model's **{detail['predicted_class']}** is "
                "retained for evaluation.",
                icon="✎",
            )
